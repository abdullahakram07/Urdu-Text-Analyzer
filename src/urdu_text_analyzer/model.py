"""Baseline sentiment model, topic discovery and evaluation."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from sklearn.decomposition import NMF
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.pipeline import Pipeline

from .data import VALID_LABELS
from .preprocessing import normalize_urdu


def _vectorizer() -> TfidfVectorizer:
    # Character n-grams tolerate Urdu spelling variation and avoid destructive tokenization.
    return TfidfVectorizer(analyzer="char", ngram_range=(2, 5), min_df=1, max_features=200_000,
                           sublinear_tf=True, norm="l2", dtype="float32")


def train_model(rows: list[dict[str, str]], seed: int = 42) -> Pipeline:
    if not rows:
        raise ValueError("Training split is empty")
    labels = {row["label"] for row in rows}
    if not labels <= VALID_LABELS or len(labels) < 2:
        raise ValueError("Training data must contain at least two valid sentiment classes")
    model = Pipeline([
        ("tfidf", _vectorizer()),
        ("classifier", LogisticRegression(max_iter=1000, class_weight="balanced", random_state=seed)),
    ])
    model.fit([normalize_urdu(row["text"]) for row in rows], [row["label"] for row in rows])
    return model


def evaluate_model(model: Pipeline, rows: list[dict[str, str]]) -> dict[str, Any]:
    if not rows:
        raise ValueError("Test split is empty")
    y_true = [row["label"] for row in rows]
    y_pred = model.predict([normalize_urdu(row["text"]) for row in rows])
    classes = sorted(set(y_true) | set(model.classes_))
    return {
        "n_test": len(rows),
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "per_class": classification_report(y_true, y_pred, labels=classes, output_dict=True,
                                            zero_division=0),
        "confusion_matrix": {"labels": classes, "counts": confusion_matrix(
            y_true, y_pred, labels=classes).tolist()},
    }


def discover_topics(texts: list[str], *, n_topics: int = 5, top_words: int = 8,
                    seed: int = 42) -> list[dict[str, Any]]:
    """Fit exploratory TF-IDF/NMF topics on unlabeled corpus text.

    Topic names are not generated by the model; returned terms require human interpretation.
    """
    clean = [normalize_urdu(text) for text in texts if normalize_urdu(text)]
    if len(clean) < 2:
        return []
    vectorizer = TfidfVectorizer(analyzer="char", ngram_range=(2, 5), min_df=1,
                                 max_features=50_000, sublinear_tf=True)
    matrix = vectorizer.fit_transform(clean)
    components = min(n_topics, max(1, matrix.shape[0] - 1), matrix.shape[1])
    if components < 1:
        return []
    nmf = NMF(n_components=components, init="nndsvda", random_state=seed, max_iter=300)
    weights = nmf.fit_transform(matrix)
    terms = vectorizer.get_feature_names_out()
    result = []
    for idx, component in enumerate(nmf.components_):
        top_indices = component.argsort()[-top_words:][::-1]
        result.append({"topic": idx, "terms": [str(terms[i]) for i in top_indices],
                       "document_count": int((weights[:, idx] >= weights.max(axis=1) * 0.5).sum())})
    return result


def predict(model: Pipeline, text: str, topics: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    clean = normalize_urdu(text)
    if not clean:
        raise ValueError("text must contain at least one non-whitespace character")
    probabilities = model.predict_proba([clean])[0]
    ranked = sorted(zip(model.classes_, probabilities), key=lambda pair: pair[1], reverse=True)
    # Topic suggestions use character n-gram overlap as an explicitly heuristic relevance score.
    suggestions = []
    if topics:
        compact = set(clean.replace(" ", ""))
        for topic in topics:
            terms = topic.get("terms", [])
            score = sum(1 for term in terms if term and term in compact)
            if score:
                suggestions.append({"topic": topic["topic"], "terms": terms, "match_count": score})
    suggestions.sort(key=lambda item: item["match_count"], reverse=True)
    return {
        "sentiment": str(ranked[0][0]),
        "confidence": float(ranked[0][1]),
        "scores": {str(label): float(score) for label, score in ranked},
        "topics": suggestions[:3],
    }


def save_model(model: Pipeline, path: Path) -> None:
    import joblib
    path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, path)


def load_model(path: Path) -> Pipeline:
    import joblib
    model = joblib.load(path)
    if not isinstance(model, Pipeline):
        raise ValueError("Model file is not a compatible analyzer pipeline")
    return model


def save_json(value: Any, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
